const { chromium, expect } = require('@playwright/test');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:19329');
  const host = browser.contexts()[0].pages().find(page => page.url().includes('tauri.localhost'));
  const invoke = (command, args = {}) => host.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  const source = await invoke('get_home_layout');
  assert.ok(source, 'This delivery check expects an existing layout');
  const original = JSON.parse(source);
  try {
    await invoke('open_tool', { tool: 'home' });
    const english = await invoke('get_locale') === 'en';
    const picker = host.locator('.widget-picker summary');
    const toggle = host.getByRole('checkbox', { name: english ? 'Favorites' : 'Preferiti', exact: true });
    const favorites = host.locator('[data-widget-id="favorites"]');
    await expect(host.locator('[data-widget-id="ai"]')).toHaveCount(0);
    await picker.click();
    await expect(host.getByRole('checkbox', { name: 'Modello AI' })).toHaveCount(0);
    await toggle.check();
    await expect(favorites).toBeVisible();
    await toggle.uncheck();
    await expect(favorites).toHaveCount(0);
    await expect.poll(async () => JSON.parse(await invoke('get_home_layout')).favoritesVisible).toBe(false);
    await host.reload();
    await expect(host.locator('[data-home-search]')).toBeVisible();
    await expect(favorites).toHaveCount(0);
    await picker.click();
    await expect(toggle).not.toBeChecked();
    await toggle.check();
    await expect(favorites).toBeVisible();
    await expect.poll(async () => JSON.parse(await invoke('get_home_layout')).favoritesVisible).toBe(true);
    const dock = host.locator('[data-widget-id="dock"]');
    const dockToggle = host.getByRole('checkbox', { name: english ? 'Quick launch' : 'Avvio rapido', exact: true });
    await dockToggle.check();
    await expect(dock).toBeVisible();
    await expect(dock.locator('.glass, footer, p')).toHaveCount(0);
    await expect(dock.locator('.app-dock')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
    await dockToggle.uncheck();
    await expect(dock).toHaveCount(0);
    await expect.poll(async () => JSON.parse(await invoke('get_home_layout')).dockVisible).toBe(false);
    await host.reload();
    await expect(host.locator('[data-home-search]')).toBeVisible();
    await expect(dock).toHaveCount(0);
    await picker.click();
    await dockToggle.check();
    await expect(dock).toBeVisible();
    await expect.poll(async () => JSON.parse(await invoke('get_home_layout')).dockVisible).toBe(true);
    await picker.click();
    const app = (await invoke('list_apps')).find(app => app.enabled && !app.hidden && !(original.dockHiddenApps ?? []).includes(app.manifest.id));
    assert.ok(app, 'Expected at least one available app for the native dock settings check');
    const options = dock.getByRole('button', { name: english ? 'Quick launch settings' : 'Impostazioni Avvio rapido', exact: true });
    const dialog = host.getByRole('dialog', { name: english ? 'Quick launch' : 'Avvio rapido', exact: true });
    await options.click();
    await dialog.getByRole('checkbox', { name: app.manifest.name, exact: true }).uncheck();
    await dialog.getByRole('button', { name: english ? 'Save' : 'Salva', exact: true }).click();
    await expect(dock.getByRole('button', { name: `Apri ${app.manifest.name}`, exact: true })).toHaveCount(0);
    await host.reload();
    await expect(host.locator('[data-home-search]')).toBeVisible();
    await expect(dock.getByRole('button', { name: `Apri ${app.manifest.name}`, exact: true })).toHaveCount(0);
    await options.click();
    await expect(dialog.getByRole('checkbox', { name: app.manifest.name, exact: true })).not.toBeChecked();
    await dialog.getByRole('checkbox', { name: app.manifest.name, exact: true }).check();
    await dialog.getByRole('button', { name: english ? 'Save' : 'Salva', exact: true }).click();
    await expect(dock.getByRole('button', { name: `Apri ${app.manifest.name}`, exact: true })).toBeVisible();
    const saved = JSON.parse(await invoke('get_home_layout'));
    delete saved.favoritesVisible; delete saved.dockVisible;
    const before = { dockHiddenApps: [], ...original }; delete before.favoritesVisible; delete before.dockVisible;
    assert.deepEqual(saved, before);
    console.log('PASS: native dock per-app settings and reload persistence, favorites/dock visibility, preserved stars and geometry');
  } finally {
    await invoke('save_home_layout', { source });
    assert.equal(await invoke('get_home_layout'), source);
    await invoke('quit_app').catch(error => { if (!/closed|destroyed|disconnected/i.test(error.message)) throw error; });
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
